export const UNITS = {
  ru: { min: 'мин', hour: 'час', day: 'день' },
  en: { min: 'min', hour: 'hour', day: 'day' }
};

export function unit(n, key) {
  return n + (UNITS[lang] || UNITS.ru)[key];
}

export const PL = {
  ru: { file: ['файл', 'файла', 'файлов'], sec: ['секунда', 'секунды', 'секунд'],
        line: ['строка', 'строки', 'строк'] },
  en: { file: ['file', 'files'], sec: ['second', 'seconds'],
        line: ['line', 'lines'] }
};

let lang = 'ru';

export function getLang() { return lang; }

export function setLangValue(l) { lang = l; }

export function t(key, ...args) {
  const d = L[lang] || L.ru;
  const s = d[key] != null ? d[key] : (L.ru[key] != null ? L.ru[key] : key);
  return String(s).replace(/\{(\d)\}/g, (_, i) => (args[+i] == null ? '' : args[+i]));
}

function ruPlural(n, one, few, many) {
  const a = n % 10, b = n % 100;
  if (a === 1 && b !== 11) return n + ' ' + one;
  if (a >= 2 && a <= 4 && (b < 10 || b >= 20)) return n + ' ' + few;
  return n + ' ' + many;
}

export function pl(n, key) {
  const f = (PL[lang] || PL.ru)[key];
  return lang === 'en' ? n + ' ' + (n === 1 ? f[0] : f[1]) : ruPlural(n, f[0], f[1], f[2]);
}

export function pickLang() {
  try {
    const s = localStorage.getItem('lambda.lang');
    if (s === 'ru' || s === 'en') return s;
  } catch (e) { /* storage may be blocked */ }
  return /^(ru|uk|be|kk)\b/i.test(navigator.language || '') ? 'ru' : 'en';
}
